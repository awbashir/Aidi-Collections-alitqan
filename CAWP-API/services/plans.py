"""Phase 3 stream B: repayment plans - preview, create, cancel, manual allocate/deallocate.

Rules (docs/phase3-spec.md "Stream B", docs/PROJECT-NOTES.md §2.5; details in
review/phase3-plans.md):

* A plan has total_amount (<= the exact outstanding balance at creation: original debt minus
  approved, non-reversed payments), frequency weekly|monthly, a Riyadh civil start_date (today
  or later), and exactly one of installment_count / installment_amount. The schedule is
  generated by services.plans_schedule (halala-exact splitting, month-end clamping).
* Plans never change the debt and never count as recovered money: nothing here writes to
  clints or "Payments".
* One active plan per case (partial unique index). A fully allocated plan closes automatically
  (stored status `completed`, db/migrations/0038), so it no longer blocks a new plan. Only an
  active plan can be cancelled (with a reason); cancelling keeps its allocations as evidence.
* Allocation: approved, non-reversed payments of the same case are allocated automatically on
  approval by the "Payments" trigger (db/migrations/0032), oldest due installment first, in a
  ledger separate from the promise ledger. Manual allocate/deallocate here need a reason.
  Capacity (per payment, per installment) is enforced by the database; its error codes are
  mapped below.
* Lock order (same as services/money.py and the triggers): the case row first
  (`FOR NO KEY UPDATE`), then the plan / allocation / payment rows.
* v2 writes run with `cawp.app_write = on` so the triggers tag their rows `api`.

Never commits: the `@idempotent()` decorator commits the route's work with its stored response.
"""
from __future__ import annotations

import datetime as _dt
from decimal import Decimal

from sqlalchemy import text
from sqlalchemy.exc import DBAPIError, IntegrityError

from core import audit, riyadh
from core.api_response import ApiError
from services import plans_schedule as sched
from services.money import (_s, approved_total, begin_app_write, db_error_code, lock_case, money,
                            optional_text, parse_amount, parse_uuid, request_meta, require_case, uid)
from services.plans_query import allocations_by_id, get_plan, plan_not_found

MAX_START_AHEAD_DAYS = 366

# database error code (0032) -> (HTTP status, api code, message)
DB_ERRORS = {
    "CW101": (409, "payment_capacity_exceeded", "the payment has no plan capacity left for this amount"),
    "CW102": (409, "installment_capacity_exceeded", "the installment has no capacity left for this amount"),
    "CW103": (409, "payment_not_allocatable", "only an approved, non-reversed payment can be allocated"),
    "CW104": (409, "plan_not_allocatable", "the plan is not active (cancelled or completed)"),
    "CW105": (422, "case_mismatch", "the payment, installment and plan must be on the same case"),
    "CW106": (404, "not_found", "payment, installment or plan not found"),
    "CW107": (409, "allocation_already_voided", "the allocation is already voided"),
    "CW108": (409, "plan_immutable", "the plan can only be cancelled once"),
}


def _raise_db(exc: DBAPIError):
    code = db_error_code(exc)
    if code in DB_ERRORS:
        status, api_code, message = DB_ERRORS[code]
        detail = getattr(getattr(exc.orig, "diag", None), "message_detail", None)
        raise ApiError(status, api_code, message,
                       {"available": money(Decimal(detail))} if detail and code in ("CW101", "CW102") else None
                       ) from None
    raise exc


# --------------------------------------------------------------------------- input
def _count_arg(value) -> int:
    if isinstance(value, bool):
        raise ApiError(422, "validation_failed", "installment_count must be an integer",
                       {"installment_count": "invalid"})
    if isinstance(value, int):
        n = value
    elif isinstance(value, str) and value.strip().isdigit():
        n = int(value.strip())
    else:
        raise ApiError(422, "validation_failed", "installment_count must be an integer",
                       {"installment_count": "invalid"})
    if n < 1:
        raise ApiError(422, "validation_failed", "installment_count must be >= 1",
                       {"installment_count": "not_positive"})
    return n


def parse_plan_body(body: dict) -> dict:
    """Validate a preview/create body and build the schedule. 422 on bad input."""
    total = parse_amount(body.get("total_amount"), "total_amount")
    frequency = body.get("frequency")
    if frequency in (None, ""):
        raise ApiError(422, "validation_failed", "frequency is required", {"frequency": "required"})
    if frequency not in sched.FREQUENCIES:
        raise ApiError(422, "validation_failed", "frequency must be weekly or monthly", {"frequency": "invalid"})
    raw_start = body.get("start_date")
    if raw_start in (None, ""):
        raise ApiError(422, "validation_failed", "start_date is required", {"start_date": "required"})
    try:
        start = riyadh.parse_date(raw_start)
    except (ValueError, TypeError):
        raise ApiError(422, "validation_failed", "start_date must be YYYY-MM-DD", {"start_date": "invalid"}) from None
    today = riyadh.today()
    if start < today:
        raise ApiError(422, "start_date_in_past", "the start date is before today (Asia/Riyadh)",
                       {"start_date": start.isoformat(), "today": today.isoformat()})
    if start > today + _dt.timedelta(days=MAX_START_AHEAD_DAYS):
        raise ApiError(422, "start_date_too_far", f"the start date is more than {MAX_START_AHEAD_DAYS} days ahead",
                       {"start_date": start.isoformat(),
                        "max": (today + _dt.timedelta(days=MAX_START_AHEAD_DAYS)).isoformat()})
    has_count = body.get("installment_count") not in (None, "")
    has_amount = body.get("installment_amount") not in (None, "")
    if has_count == has_amount:
        raise ApiError(422, "validation_failed", "give exactly one of installment_count or installment_amount",
                       {"installment_count": "exactly_one_of", "installment_amount": "exactly_one_of"})
    count = _count_arg(body["installment_count"]) if has_count else None
    inst_amount = parse_amount(body["installment_amount"], "installment_amount") if has_amount else None
    try:
        schedule = sched.build_schedule(total, frequency, start, installment_count=count,
                                        installment_amount=inst_amount)
    except sched.ScheduleError as e:
        error = {e.field: "invalid"} if e.code == "validation_failed" else {"field": e.field, **(e.detail or {})}
        raise ApiError(422, e.code, e.message, error) from None
    return {
        "total_amount": total, "frequency": frequency, "start_date": start,
        "split_mode": "count" if has_count else "amount", "installment_amount": inst_amount,
        "installment_count": len(schedule), "schedule": schedule,
        "note": optional_text(body, "note", 2000),
    }


def _schedule_json(parsed: dict) -> list[dict]:
    return [{"seq": i["seq"], "due_date": i["due_date"].isoformat(), "amount": money(i["amount"])}
            for i in parsed["schedule"]]


def _rules(parsed: dict) -> dict:
    return {
        "split": ("remainder_spread_from_first" if parsed["split_mode"] == "count" else "equal_with_smaller_last"),
        "due_dates": ("every_7_days" if parsed["frequency"] == "weekly"
                      else "same_day_each_month_clamped_to_month_end"),
    }


# --------------------------------------------------------------------------- case checks
def _case_checks(case_id, parsed: dict, *, lock: bool) -> dict:
    """Case not locked (423), total <= exact outstanding (409), no active plan (409)."""
    if lock:
        case = lock_case(case_id)
    else:
        case = _s().execute(text("SELECT id, round(amount::numeric, 2) AS original, is_locked "
                                 "FROM clints WHERE id = CAST(:cid AS uuid)"), {"cid": str(case_id)}).mappings().first()
        if case is None:
            raise ApiError(404, "case_not_found", "case not found", {"case_id": str(case_id)})
    if case["is_locked"]:
        raise ApiError(423, "case_locked", "the case is locked", {"case_id": str(case_id)})
    approved = approved_total(case_id)
    outstanding = case["original"] - approved
    balance = {"original": money(case["original"]), "approved": money(approved), "outstanding": money(outstanding)}
    if parsed["total_amount"] > outstanding:
        raise ApiError(409, "amount_exceeds_balance", "the plan total exceeds the outstanding balance",
                       {**balance, "total_amount": money(parsed["total_amount"])})
    active = _s().execute(text("SELECT plan_id, state FROM v_plan_state "
                               "WHERE case_id = CAST(:cid AS uuid) AND status = 'active'"),
                          {"cid": str(case_id)}).mappings().first()
    if active is not None:
        raise ApiError(409, "plan_already_active", "the case already has an active repayment plan",
                       {"plan_id": str(active["plan_id"]), "state": active["state"]})
    return {"outstanding": outstanding, "balance": balance}


# --------------------------------------------------------------------------- preview / create
def preview_plan(case_id, scope, body) -> dict:
    """The schedule a create with the same body would save. Nothing is written."""
    parsed = parse_plan_body(body)
    require_case(case_id, scope)
    checks = _case_checks(case_id, parsed, lock=False)
    return {
        "case_id": str(case_id),
        "frequency": parsed["frequency"],
        "start_date": parsed["start_date"].isoformat(),
        "end_date": parsed["schedule"][-1]["due_date"].isoformat(),
        "total_amount": money(parsed["total_amount"]),
        "installment_count": parsed["installment_count"],
        "split_mode": parsed["split_mode"],
        "installment_amount": money(parsed["installment_amount"]),
        "installments": _schedule_json(parsed),
        "balance": checks["balance"],
        "rules": _rules(parsed),
    }


def _plan_event(plan_id, case_id, event, actor, amount=None, reason=None, installment_id=None,
                allocation_id=None, payment_id=None, details=None):
    req_id, key = request_meta()
    _s().execute(text("""
        INSERT INTO plan_events (plan_id, case_id, event, actor_user_id, amount, reason, installment_id,
                                 allocation_id, payment_id, details, source, request_id, idempotency_key)
        VALUES (CAST(:plan AS uuid), CAST(:cid AS uuid), :ev, CAST(:actor AS uuid), :amount, :reason,
                CAST(:inst AS uuid), CAST(:aid AS uuid), CAST(:pay AS uuid), CAST(:details AS jsonb),
                'api', :req, :key)
    """), {"plan": str(plan_id), "cid": str(case_id), "ev": event, "actor": uid(actor), "amount": amount,
           "reason": reason, "inst": uid(installment_id), "aid": uid(allocation_id), "pay": uid(payment_id),
           "details": audit.to_json(details), "req": req_id, "key": key})


def create_plan(case_id, actor, scope, body) -> dict:
    parsed = parse_plan_body(body)
    begin_app_write()
    require_case(case_id, scope)
    checks = _case_checks(case_id, parsed, lock=True)
    req_id, key = request_meta()
    try:
        with _s().begin_nested():
            plan_id = _s().execute(text("""
                INSERT INTO repayment_plans (case_id, frequency, start_date, total_amount, installment_count,
                                             split_mode, installment_amount, outstanding_at_creation, note,
                                             created_by, request_id, idempotency_key)
                VALUES (CAST(:cid AS uuid), :freq, :start, :total, :n, :mode, :inst_amount, :outstanding, :note,
                        CAST(:actor AS uuid), :req, :key)
                RETURNING id
            """), {"cid": str(case_id), "freq": parsed["frequency"], "start": parsed["start_date"],
                   "total": parsed["total_amount"], "n": parsed["installment_count"],
                   "mode": parsed["split_mode"], "inst_amount": parsed["installment_amount"],
                   "outstanding": checks["outstanding"], "note": parsed["note"], "actor": str(actor),
                   "req": req_id, "key": key}).scalar()
    except IntegrityError as e:
        if db_error_code(e) == "23505":
            # uq_repayment_plans_one_active: a completed plan of this case was reopened by a
            # concurrent void (a reversal / legacy reject that holds no case lock) and committed first
            active = _s().execute(text("SELECT plan_id, state FROM v_plan_state "
                                       "WHERE case_id = CAST(:cid AS uuid) AND status = 'active'"),
                                  {"cid": str(case_id)}).mappings().first()
            raise ApiError(409, "plan_already_active", "the case already has an active repayment plan",
                           {"plan_id": str(active["plan_id"]) if active else None,
                            "state": active["state"] if active else None}) from None
        raise
    _s().execute(text("""
        INSERT INTO plan_installments (plan_id, case_id, seq, due_date, amount)
        VALUES (CAST(:plan AS uuid), CAST(:cid AS uuid), :seq, :due, :amount)
    """), [{"plan": str(plan_id), "cid": str(case_id), "seq": i["seq"], "due": i["due_date"],
            "amount": i["amount"]} for i in parsed["schedule"]])
    # check the deferred schedule constraint now, inside the request, not at commit
    _s().execute(text("SET CONSTRAINTS repayment_plans_schedule_check IMMEDIATE"))
    summary = {"total_amount": money(parsed["total_amount"]), "frequency": parsed["frequency"],
               "start_date": parsed["start_date"].isoformat(),
               "end_date": parsed["schedule"][-1]["due_date"].isoformat(),
               "installment_count": parsed["installment_count"], "split_mode": parsed["split_mode"],
               "installment_amount": money(parsed["installment_amount"]),
               "outstanding_at_creation": money(checks["outstanding"])}
    _plan_event(plan_id, case_id, "created", actor, parsed["total_amount"], details=summary)
    audit.record("plan.create", "repayment_plan", plan_id, case_id=case_id,
                 after={**summary, "note": parsed["note"], "installments": _schedule_json(parsed)})
    return get_plan(plan_id)


# --------------------------------------------------------------------------- cancel
def _plan_case_id(plan_id):
    row = _s().execute(text("SELECT case_id FROM repayment_plans WHERE id = CAST(:pid AS uuid)"),
                       {"pid": str(plan_id)}).first()
    if row is None:
        code, message, error = plan_not_found(plan_id)
        raise ApiError(404, code, message, error)
    return row[0]


def cancel_plan(plan_id, actor, scope, expected_revision, reason) -> dict:
    begin_app_write()
    case_id = _plan_case_id(plan_id)
    require_case(case_id, scope, plan_not_found(plan_id))
    lock_case(case_id)
    row = _s().execute(text("SELECT revision, status FROM repayment_plans WHERE id = CAST(:pid AS uuid) FOR UPDATE"),
                       {"pid": str(plan_id)}).mappings().one()
    if expected_revision is not None and row["revision"] != expected_revision:
        from core.revisions import RevisionConflict
        raise RevisionConflict("plan", plan_id, expected_revision, row["revision"])
    if row["status"] != "active":
        raise ApiError(409, "plan_not_cancellable", f"a {row['status']} plan cannot be cancelled",
                       {"state": row["status"]})
    before = _s().execute(text("SELECT state, allocated FROM v_plan_state WHERE plan_id = CAST(:pid AS uuid)"),
                          {"pid": str(plan_id)}).mappings().one()
    _s().execute(text("""
        UPDATE repayment_plans
           SET status = 'cancelled', cancelled_at = now(), cancelled_by = CAST(:actor AS uuid), cancel_reason = :reason
         WHERE id = CAST(:pid AS uuid)
    """), {"actor": str(actor), "reason": reason, "pid": str(plan_id)})
    _plan_event(plan_id, case_id, "cancelled", actor, reason=reason,
                details={"state_before": before["state"], "allocated": money(before["allocated"])})
    audit.record("plan.cancel", "repayment_plan", plan_id, case_id=case_id,
                 before={"state": before["state"]}, after={"state": "cancelled"}, reason=reason)
    return get_plan(plan_id)


# --------------------------------------------------------------------------- manual allocation
def allocate(plan_id, actor, scope, body, reason) -> dict:
    """Allocate an approved payment of the plan's case to one installment (installment_id) or
    to the plan's unpaid installments oldest due first. Without `amount`: as much as both sides
    allow."""
    payment_id = parse_uuid(body.get("payment_id"), "payment_id")
    installment_id = (parse_uuid(body.get("installment_id"), "installment_id")
                      if body.get("installment_id") not in (None, "") else None)
    amount = parse_amount(body.get("amount")) if body.get("amount") not in (None, "") else None
    begin_app_write()
    case_id = _plan_case_id(plan_id)
    require_case(case_id, scope, plan_not_found(plan_id))
    lock_case(case_id)
    status = _s().execute(text("SELECT status FROM repayment_plans WHERE id = CAST(:pid AS uuid)"),
                          {"pid": str(plan_id)}).scalar()
    if status != "active":
        raise ApiError(409, "plan_not_allocatable", f"a {status} plan takes no new allocations",
                       {"state": status})
    pay = _s().execute(text("""
        SELECT p.clint_id, round(p.amount::numeric, 2) AS amount, p.approval_status, p.is_deleted,
               EXISTS (SELECT 1 FROM payment_reversals r WHERE r.payment_id = p.id) AS reversed,
               (SELECT coalesce(sum(a.amount), 0) FROM plan_allocations a
                 WHERE a.payment_id = p.id AND a.voided_at IS NULL) AS plan_allocated
          FROM "Payments" p WHERE p.id = CAST(:pay AS uuid)
    """), {"pay": payment_id}).mappings().first()
    if pay is None:
        raise ApiError(404, "payment_not_found", "payment not found", {"payment_id": payment_id})
    if str(pay["clint_id"]) != str(case_id):
        raise ApiError(422, "case_mismatch", "the payment is on another case",
                       {"payment_id": payment_id, "case_id": str(case_id)})
    if pay["reversed"] or pay["is_deleted"] or pay["approval_status"] is not True:
        pstatus = ("reversed" if pay["reversed"] else "deleted" if pay["is_deleted"]
                   else "pending" if pay["approval_status"] is None else "rejected")
        raise ApiError(409, "payment_not_allocatable", "only an approved, non-reversed payment can be allocated",
                       {"status": pstatus})
    free = max(pay["amount"] - pay["plan_allocated"], Decimal(0))
    targets = _s().execute(text("""
        SELECT installment_id, remaining FROM v_plan_installment_state
         WHERE plan_id = CAST(:pid AS uuid) AND (CAST(:iid AS uuid) IS NULL OR installment_id = CAST(:iid AS uuid))
         ORDER BY due_date, seq
    """), {"pid": str(plan_id), "iid": installment_id}).mappings().all()
    if installment_id and not targets:
        raise ApiError(404, "installment_not_found", "installment not found in this plan",
                       {"installment_id": installment_id})
    capacity = sum((t["remaining"] for t in targets), Decimal(0))
    if amount is None:
        amount = min(free, capacity)
        if amount <= 0:
            raise ApiError(409, "nothing_to_allocate", "the payment or the installments have no capacity left",
                           {"payment_available": money(free), "installments_available": money(capacity)})
    elif amount > free:
        raise ApiError(409, "payment_capacity_exceeded", "the payment has no plan capacity left for this amount",
                       {"available": money(free)})
    elif amount > capacity:
        raise ApiError(409, "installment_capacity_exceeded", "the installments have no capacity left for this amount",
                       {"available": money(capacity)})
    created, left = [], amount
    try:
        with _s().begin_nested():
            for t in targets:
                if left <= 0:
                    break
                if t["remaining"] <= 0:
                    continue
                take = min(left, t["remaining"])
                aid = _s().execute(text("""
                    INSERT INTO plan_allocations (plan_id, installment_id, payment_id, case_id, amount, source,
                                                  note, created_by)
                    VALUES (CAST(:plan AS uuid), CAST(:inst AS uuid), CAST(:pay AS uuid), CAST(:cid AS uuid),
                            :amount, 'manual', :note, CAST(:actor AS uuid))
                    RETURNING id
                """), {"plan": str(plan_id), "inst": str(t["installment_id"]), "pay": payment_id,
                       "cid": str(case_id), "amount": take, "note": reason, "actor": str(actor)}).scalar()
                created.append((aid, t["installment_id"], take))
                left -= take
    except DBAPIError as e:
        _raise_db(e)
    for aid, inst, take in created:
        _plan_event(plan_id, case_id, "allocated", actor, take, reason=reason, installment_id=inst,
                    allocation_id=aid, payment_id=payment_id)
    allocations = allocations_by_id([a[0] for a in created])
    audit.record("plan.allocate", "repayment_plan", plan_id, case_id=case_id,
                 after={"payment_id": payment_id, "amount": money(amount), "source": "manual",
                        "allocations": [{"id": a["id"], "installment_id": a["installment_id"],
                                         "amount": a["amount"]} for a in allocations]},
                 reason=reason)
    return {"allocations": allocations, "plan": get_plan(plan_id)}


def deallocate(allocation_id, actor, scope, reason) -> dict:
    begin_app_write()
    row = _s().execute(text("SELECT case_id, plan_id FROM plan_allocations WHERE id = CAST(:aid AS uuid)"),
                       {"aid": str(allocation_id)}).mappings().first()
    not_found = ("allocation_not_found", "allocation not found", {"allocation_id": str(allocation_id)})
    if row is None:
        raise ApiError(404, *not_found)
    case_id, plan_id = row["case_id"], row["plan_id"]
    require_case(case_id, scope, not_found)
    lock_case(case_id)
    a = _s().execute(text("""
        SELECT id, installment_id, payment_id, amount, voided_at FROM plan_allocations
         WHERE id = CAST(:aid AS uuid) FOR UPDATE
    """), {"aid": str(allocation_id)}).mappings().one()
    if a["voided_at"] is not None:
        raise ApiError(409, "allocation_already_voided", "the allocation is already voided",
                       {"voided_at": a["voided_at"].isoformat()})
    _s().execute(text("""
        UPDATE plan_allocations SET voided_at = now(), voided_by = CAST(:actor AS uuid), void_reason = :reason
         WHERE id = CAST(:aid AS uuid)
    """), {"actor": str(actor), "reason": reason, "aid": str(allocation_id)})
    _plan_event(plan_id, case_id, "deallocated", actor, a["amount"], reason=reason,
                installment_id=a["installment_id"], allocation_id=allocation_id, payment_id=a["payment_id"])
    audit.record("plan.deallocate", "plan_allocation", allocation_id, case_id=case_id,
                 before={"active": True, "amount": money(a["amount"])}, after={"active": False},
                 reason=reason)
    return {"allocation_id": str(allocation_id), "plan": get_plan(plan_id)}
