"""Generated dialplan for the AI calling agent test (0092, docs/alitqan-ai-calling-agent-plan.md):
`python -m services.calling.ai_dialplan < policy.json > /etc/asterisk/collections-ai.conf`.

The AI voice service (on the app server) sends a SIP INVITE to `cawp-ai-agent` as ONE dedicated
extension, with the call id and a one-shot token in SIP headers. `from-internal` includes
`from-internal-custom`, so the call lands here:

1. [collections-ai-dial] refuses any caller but the agent extension (CHANNEL(peername)), reads the
   headers, asks the FastAGI hook `collections-ai-authorize` (token bound to the call, one use,
   short-lived) and takes the number to dial and the outbound number from the hook only; the
   calling window; the national number; the first trunk whose SIPPEER status is OK; the trunk's
   caller ID or the chosen outbound number; ONE Dial, never another trunk, limited to
   max_call_seconds. The agent's leg is answered only when the client answers (Dial).
2. Whatever ends the Dial, the agent's leg gets a cause the SIP answer carries: busy 486, no answer
   480, congestion / unavailable / no trunk 503, denied 403.

Globals (protected include file): COLLECTIONS_MSG_AGI (agi://<calling host>:4573), COLLECTIONS_AGI_KEY.
"""
from __future__ import annotations

import json
import re
import sys

from services.calling.windows import WindowError, dialplan_time_ranges, validate_windows

KEYS = {"trunks", "issabel_trunk_ids", "ring_seconds", "max_call_seconds", "agent_extension", "record",
        "calling_windows"}
TRUNK_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
EXT_RE = re.compile(r"^[0-9]{2,6}$")
LIMITS = {"ring_seconds": (1, 60), "max_call_seconds": (30, 600)}
UUID_CHECK = '$[${REGEX("^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$" ${%s})} != 1]'
AGENT_EXTEN = "cawp-ai-agent"


class AiDialplanError(ValueError):
    pass


def validate(policy) -> dict:
    if not isinstance(policy, dict) or set(policy) != KEYS:
        raise AiDialplanError("policy must be an object with exactly: " + ", ".join(sorted(KEYS)))
    trunks = policy["trunks"]
    if (not isinstance(trunks, list) or not 1 <= len(trunks) <= 16 or len(set(trunks)) != len(trunks)
            or any(not isinstance(t, str) or not TRUNK_RE.match(t) for t in trunks)):
        raise AiDialplanError("trunks must be 1..16 distinct names matching [A-Za-z0-9_-]{1,64}")
    ids = policy["issabel_trunk_ids"]
    if (not isinstance(ids, dict) or set(ids) != set(trunks)
            or any(not isinstance(n, int) or isinstance(n, bool) or not 1 <= n <= 9999 for n in ids.values())):
        raise AiDialplanError("issabel_trunk_ids must map every trunk to its IssabelPBX trunk number")
    for k, (lo, hi) in LIMITS.items():
        v = policy[k]
        if isinstance(v, bool) or not isinstance(v, int) or not lo <= v <= hi:
            raise AiDialplanError(f"{k} must be an integer {lo}..{hi}")
    if not isinstance(policy["agent_extension"], str) or not EXT_RE.match(policy["agent_extension"]):
        raise AiDialplanError("agent_extension must be the agent's extension number")
    if not isinstance(policy["record"], bool):
        raise AiDialplanError("record must be true or false")
    try:
        windows = validate_windows(policy["calling_windows"])
    except WindowError as e:
        raise AiDialplanError(f"calling_windows: {e}") from None
    return {**policy, "calling_windows": windows}


def render(policy) -> str:
    p = validate(policy)
    trunks, ids, ext = p["trunks"], p["issabel_trunk_ids"], p["agent_extension"]
    ranges = dialplan_time_ranges(p["calling_windows"])
    lines = [
        "; Generated by `python -m services.calling.ai_dialplan` (CAWP AI calling agent test, 0092).",
        "; Review before installation. Regenerate instead of editing by hand.",
        f"; policy: agent_extension={ext} trunks={','.join(f'{t}:{ids[t]}' for t in trunks)}"
        f" ring_seconds={p['ring_seconds']} max_call_seconds={p['max_call_seconds']}"
        f" record={'yes' if p['record'] else 'no'}",
        f"; calling_windows (Asia/Riyadh, end exclusive): {json.dumps(p['calling_windows'], separators=(',', ':'))}",
        "; Reachable only by the agent extension with a token the FastAGI hook accepts.",
        "; Required [globals]: COLLECTIONS_MSG_AGI (agi://<calling host>:4573), COLLECTIONS_AGI_KEY.",
        "",
        "[from-internal-custom]",
        f"exten => {AGENT_EXTEN},1,Goto(collections-ai-dial,s,1)",
        "",
        "[collections-ai-dial]",
        "exten => s,1,Set(COLLECTIONS_AI_GATE=)",
        " same => n,Set(COLLECTIONS_AI_DESTINATION=)",
        " same => n,Set(COLLECTIONS_AI_CID=)",
        f' same => n,GotoIf($["${{CHANNEL(peername)}}" != "{ext}"]?deny)',
        " same => n,Set(COLLECTIONS_AI_CALL=${SIP_HEADER(X-CAWP-Call)})",
        " same => n,Set(COLLECTIONS_AI_TOKEN=${SIP_HEADER(X-CAWP-Token)})",
        f" same => n,GotoIf({UUID_CHECK % 'COLLECTIONS_AI_CALL'}?deny)",
        " same => n,AGI(${GLOBAL(COLLECTIONS_MSG_AGI)}/collections-ai-authorize)",
        " same => n,Set(COLLECTIONS_AI_TOKEN=)",
        ' same => n,GotoIf($["${AGISTATUS}" != "SUCCESS"]?deny)',
        ' same => n,GotoIf($["${COLLECTIONS_AI_GATE}" != "ALLOW"]?deny)',
        ' same => n,GotoIf($[${REGEX("^[+]966[0-9]{9}$" ${COLLECTIONS_AI_DESTINATION})} != 1]?deny)',
        *[f" same => n,GotoIfTime({r['time']},{r['weekday']},*,*,Asia/Riyadh?window)" for r in ranges],
        " same => n,Goto(deny)",
        " same => n(window),Set(COLLECTIONS_DIAL_NUMBER=0${COLLECTIONS_AI_DESTINATION:4})",
        ' same => n,GotoIf($[${REGEX("^0[0-9]{9}$" ${COLLECTIONS_DIAL_NUMBER})} != 1]?deny)',
    ]
    for t in trunks:                      # COLLECTIONS_TRUNK is only ever set from these constants
        lines += [
            f" same => n,Set(COLLECTIONS_TRUNK={t})",
            f" same => n,Set(COLLECTIONS_TRUNK_ID={ids[t]})",
            f' same => n,GotoIf($["${{SIPPEER({t},status):0:2}}" = "OK"]?trunk)',
        ]
    lines += [
        " same => n,Goto(notrunk)",
        " same => n(trunk),Set(COLLECTIONS_CID=${GLOBAL(OUTCID_${COLLECTIONS_TRUNK_ID})})",
        " same => n,ExecIf($[${LEN(${GLOBAL(FORCEDOUTCID_${COLLECTIONS_TRUNK_ID})})} != 0]"
        "?Set(COLLECTIONS_CID=${GLOBAL(FORCEDOUTCID_${COLLECTIONS_TRUNK_ID})}))",
        " same => n,ExecIf($[${LEN(${COLLECTIONS_CID})} != 0]?Set(CALLERID(all)=${COLLECTIONS_CID}))",
        ' same => n,ExecIf($[${REGEX("^[+]966[0-9]{9}$" ${COLLECTIONS_AI_CID})} = 1]?Set(CALLERID(all)=${COLLECTIONS_AI_CID}))',
        " same => n,Set(CDR(outbound_cnum)=${CALLERID(num)})",
        " same => n,Set(CDR(userfield)=cawp-ai:${COLLECTIONS_AI_CALL})",
    ]
    if p["record"]:
        lines += [
            " same => n,Set(COLLECTIONS_AI_REC=${STRFTIME(${EPOCH},Asia/Riyadh,%Y/%m/%d)}/cawp-ai-${COLLECTIONS_AI_CALL}.wav)",
            " same => n,Set(CDR(recordingfile)=${COLLECTIONS_AI_REC})",
            " same => n,MixMonitor(${COLLECTIONS_AI_REC})",
        ]
    lines += [
        f" same => n,Set(TIMEOUT(absolute)={p['max_call_seconds'] + p['ring_seconds'] + 10})",
        f" same => n,Dial(SIP/${{COLLECTIONS_TRUNK}}/${{COLLECTIONS_DIAL_NUMBER}},{p['ring_seconds']},"
        f"L({p['max_call_seconds'] * 1000}))",
        ' same => n,GotoIf($["${DIALSTATUS}" = "BUSY"]?busy)',
        ' same => n,GotoIf($["${DIALSTATUS}" = "NOANSWER"]?noanswer)',
        ' same => n,GotoIf($["${DIALSTATUS}" = "ANSWER"]?done)',
        " same => n,Hangup(34)",                      # congestion / unavailable: 503
        " same => n(busy),Hangup(17)",                # 486
        " same => n(noanswer),Hangup(19)",            # 480
        " same => n(done),Hangup(16)",
        " same => n(notrunk),Hangup(34)",
        " same => n(deny),Hangup(21)",                # 403
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    data = sys.stdin.read(65536 + 1)
    if len(data) > 65536:
        print("policy is larger than 64 KiB", file=sys.stderr)
        return 2
    try:
        sys.stdout.write(render(json.loads(data)))
    except (ValueError, AiDialplanError) as e:
        print(f"invalid policy: {e}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
