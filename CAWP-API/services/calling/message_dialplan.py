"""Message-campaign dialplan generator (customer request 2026-10-25, migration 0088,
docs/alitqan-message-campaigns-plan.md). Asterisk 11 / chan_sip (the Alitqan Issabel).

    python -m services.calling.message_dialplan < policy.json > /etc/asterisk/collections-message.conf

Policy (JSON): trunks (["Mobily18", ...], the first reachable one is dialled once), issabel_trunk_ids
({"Mobily18": 2, ...}: the caller ID is the trunk's OUTCID_N, FORCEDOUTCID_N over it), ring_seconds
(1..60), max_call_seconds (60..3600), transfer_wait_seconds (10..300: how long a "1" waits for a
free member, hold music), member_ring_seconds (5..60), record (bool), calling_windows (Riyadh
windows, services/calling/windows.py).

How a message call flows (the calling service sends ONE Originate per call,
services/calling/message_campaign.py):

    Originate Channel=Local/<+E164>@collections-message-dial/n  Context=collections-message-ivr  Exten=s
              Variables: __COLLECTIONS_MSG_CALL, __COLLECTIONS_MSG_CAMPAIGN, COLLECTIONS_MSG_TOKEN,
                         COLLECTIONS_MSG_TRANSFER (1/0), COLLECTIONS_MSG_GOODBYE (1/0)

1. Local;2 runs [collections-message-dial]: the FastAGI hook `collections-message-authorize`
   consumes the one-shot token (bound to this call, its destination and the PBX epoch) and only
   then sets COLLECTIONS_MSG_GATE=ALLOW; every gate output is re-checked; the calling window; the
   national number; the first trunk whose SIPPEER status is OK; the trunk's caller ID; ONE Dial,
   never another trunk. Its hangup handler reports DIALSTATUS.
2. The client answers -> Local;1 runs [collections-message-ivr]: the message (sounds
   cawp/<campaign>-message, played COLLECTIONS_MSG_PLAYS_MAX times at most: 1..5, default 2), one key read: 2 -> goodbye, 1 (when enabled) ->
   the hook `collections-message-agent` names a free campaign member, whose extension is rung with
   hold music; nobody free / no answer until transfer_wait_seconds -> the callback message.
3. Every step is a `UserEvent(CollectionsMessage, CallId, State, ...)`; the calling service
   records them (message_calls). The click-to-call evidence ignores this event name.
Globals (protected include file, never channel variables): COLLECTIONS_MSG_AGI =
agi://<calling host>:4573 and COLLECTIONS_AGI_KEY (the shared secret, as for click-to-call).
"""
from __future__ import annotations

import json
import re
import sys

from services.calling.windows import WindowError, dialplan_time_ranges, validate_windows

KEYS = {"trunks", "issabel_trunk_ids", "ring_seconds", "max_call_seconds", "transfer_wait_seconds",
        "member_ring_seconds", "record", "calling_windows"}
TRUNK_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
LIMITS = {"ring_seconds": (1, 60), "max_call_seconds": (60, 3600), "transfer_wait_seconds": (10, 300),
          "member_ring_seconds": (5, 60)}
UUID_CHECK = '$[${REGEX("^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$" ${%s})} != 1]'


class MessageDialplanError(ValueError):
    pass


def validate(policy) -> dict:
    if not isinstance(policy, dict) or set(policy) != KEYS:
        raise MessageDialplanError("policy must be an object with exactly: " + ", ".join(sorted(KEYS)))
    trunks = policy["trunks"]
    if (not isinstance(trunks, list) or not 1 <= len(trunks) <= 16 or len(set(trunks)) != len(trunks)
            or any(not isinstance(t, str) or not TRUNK_RE.match(t) for t in trunks)):
        raise MessageDialplanError("trunks must be 1..16 distinct names matching [A-Za-z0-9_-]{1,64}")
    ids = policy["issabel_trunk_ids"]
    if (not isinstance(ids, dict) or set(ids) != set(trunks)
            or any(not isinstance(n, int) or isinstance(n, bool) or not 1 <= n <= 9999 for n in ids.values())):
        raise MessageDialplanError("issabel_trunk_ids must map every trunk to its IssabelPBX trunk number")
    for k, (lo, hi) in LIMITS.items():
        v = policy[k]
        if isinstance(v, bool) or not isinstance(v, int) or not lo <= v <= hi:
            raise MessageDialplanError(f"{k} must be an integer {lo}..{hi}")
    if not isinstance(policy["record"], bool):
        raise MessageDialplanError("record must be true or false")
    try:
        windows = validate_windows(policy["calling_windows"])
    except WindowError as e:
        raise MessageDialplanError(f"calling_windows: {e}") from None
    return {**policy, "calling_windows": windows}


def _ev(state: str, extra: str = "") -> str:
    return f"UserEvent(CollectionsMessage,CallId: ${{COLLECTIONS_MSG_CALL}},ChanUniqueid: ${{UNIQUEID}},State: {state}{extra})"


def render(policy) -> str:
    p = validate(policy)
    trunks, ids = p["trunks"], p["issabel_trunk_ids"]
    agi = "${GLOBAL(COLLECTIONS_MSG_AGI)}"
    ranges = dialplan_time_ranges(p["calling_windows"])
    lines = [
        "; Generated by `python -m services.calling.message_dialplan` (CAWP message campaigns, 0088).",
        "; Review before installation. Regenerate instead of editing by hand.",
        f"; policy: trunks={','.join(f'{t}:{ids[t]}' for t in trunks)} ring_seconds={p['ring_seconds']}"
        f" max_call_seconds={p['max_call_seconds']} transfer_wait_seconds={p['transfer_wait_seconds']}"
        f" member_ring_seconds={p['member_ring_seconds']} record={'yes' if p['record'] else 'no'}",
        f"; calling_windows (Asia/Riyadh, end exclusive): {json.dumps(p['calling_windows'], separators=(',', ':'))}",
        "; Reachable only from the calling service's Originate (Local/<+E164>@collections-message-dial/n).",
        "; Never include these contexts in an endpoint's own dialing context.",
        "; Required [globals]: COLLECTIONS_MSG_AGI (agi://<calling host>:4573), COLLECTIONS_AGI_KEY.",
        "",
        "; Local;2: the gate, the trunk, ONE Dial of the client.",
        "[collections-message-dial]",
        "exten => _+X.,1,Set(COLLECTIONS_MSG_GATE=)",
        " same => n,Set(COLLECTIONS_MSG_DESTINATION=)",
        " same => n,Set(COLLECTIONS_MSG_FAIL=)",
        " same => n,Set(CHANNEL(hangup_handler_push)=collections-message-dial-end,s,1)",
        f" same => n,GotoIf({UUID_CHECK % 'COLLECTIONS_MSG_CALL'}?deny)",
        f" same => n,AGI({agi}/collections-message-authorize)",
        " same => n,Set(COLLECTIONS_MSG_TOKEN=)",
        ' same => n,GotoIf($["${AGISTATUS}" != "SUCCESS"]?deny)',
        ' same => n,GotoIf($["${COLLECTIONS_MSG_GATE}" != "ALLOW"]?deny)',
        ' same => n,GotoIf($["${COLLECTIONS_MSG_DESTINATION}" != "${EXTEN}"]?deny)',
        ' same => n,GotoIf($[${REGEX("^[+]966[0-9]{9}$" ${EXTEN})} != 1]?deny)',
        *[f" same => n,GotoIfTime({r['time']},{r['weekday']},*,*,Asia/Riyadh?window)" for r in ranges],
        " same => n,Goto(deny)",
        " same => n(window),Set(COLLECTIONS_DIAL_NUMBER=0${EXTEN:4})",
        ' same => n,GotoIf($[${REGEX("^0[0-9]{9}$" ${COLLECTIONS_DIAL_NUMBER})} != 1]?deny)',
    ]
    for t in trunks:                      # COLLECTIONS_TRUNK is only ever set from these constants
        lines += [
            f" same => n,Set(COLLECTIONS_TRUNK={t})",
            f" same => n,Set(COLLECTIONS_TRUNK_ID={ids[t]})",
            f' same => n,GotoIf($["${{SIPPEER({t},status):0:2}}" = "OK"]?trunk)',
        ]
    lines += [
        " same => n,Set(COLLECTIONS_TRUNK=)",
        " same => n,Goto(notrunk)",
        " same => n(trunk),Set(COLLECTIONS_CID=${GLOBAL(OUTCID_${COLLECTIONS_TRUNK_ID})})",
        " same => n,ExecIf($[${LEN(${GLOBAL(FORCEDOUTCID_${COLLECTIONS_TRUNK_ID})})} != 0]"
        "?Set(COLLECTIONS_CID=${GLOBAL(FORCEDOUTCID_${COLLECTIONS_TRUNK_ID})}))",
        " same => n,ExecIf($[${LEN(${COLLECTIONS_CID})} != 0]?Set(CALLERID(all)=${COLLECTIONS_CID}))",
        " same => n,Set(CDR(outbound_cnum)=${CALLERID(num)})",
        " same => n,Set(CDR(userfield)=cawp-msg:${COLLECTIONS_MSG_CALL})",
        f" same => n,{_ev('dialing', ',Trunk: ${COLLECTIONS_TRUNK}')}",
        f" same => n,Dial(SIP/${{COLLECTIONS_TRUNK}}/${{COLLECTIONS_DIAL_NUMBER}},{p['ring_seconds']},"
        f"iL({p['max_call_seconds'] * 1000}))",
        " same => n,Hangup()",                        # any DIALSTATUS ends the call: never another trunk
        " same => n(notrunk),Set(COLLECTIONS_MSG_FAIL=no_trunk)",
        " same => n,Hangup(34)",
        " same => n(deny),Set(COLLECTIONS_MSG_FAIL=denied)",
        " same => n,Hangup(21)",
        "exten => i,1,Hangup(21)",
        "",
        "; Hangup handler of Local;2: the dial's result (an answered call reports ANSWER at its end).",
        "[collections-message-dial-end]",
        f"exten => s,1,{_ev('dial_end', ',DialStatus: ${DIALSTATUS},Fail: ${COLLECTIONS_MSG_FAIL},Cause: ${HANGUPCAUSE}')}",
        " same => n,Return()",
        "",
        "; Local;1 once the client answered: the message, one key, the member, the callback message.",
        "[collections-message-ivr]",
        "exten => s,1,Set(CHANNEL(hangup_handler_push)=collections-message-ivr-end,s,1)",
        f" same => n,Set(TIMEOUT(absolute)={p['max_call_seconds']})",
        f" same => n,GotoIf({UUID_CHECK % 'COLLECTIONS_MSG_CALL'}?bye)",
        f" same => n,GotoIf({UUID_CHECK % 'COLLECTIONS_MSG_CAMPAIGN'}?bye)",
        " same => n,Set(COLLECTIONS_MSG_SOUND=cawp/${COLLECTIONS_MSG_CAMPAIGN})",
    ]
    if p["record"]:
        lines += [
            " same => n,Set(COLLECTIONS_MSG_REC=${STRFTIME(${EPOCH},Asia/Riyadh,%Y/%m/%d)}/cawp-msg-${COLLECTIONS_MSG_CALL}.wav)",
            " same => n,Set(CDR(recordingfile)=${COLLECTIONS_MSG_REC})",
            " same => n,MixMonitor(${COLLECTIONS_MSG_REC})",
            f" same => n,{_ev('answered', ',Recording: ${COLLECTIONS_MSG_REC}')}",
        ]
    else:
        lines.append(f" same => n,{_ev('answered')}")
    lines += [
        " same => n,Wait(0.5)",
        " same => n,Set(COLLECTIONS_MSG_PLAYS=0)",
        # the campaign's play count (Originate variable, 1..5); anything else -> 2 (0089)
        " same => n,Set(COLLECTIONS_MSG_MAX=2)",
        ' same => n,ExecIf($[${REGEX("^[1-5]$" ${COLLECTIONS_MSG_PLAYS_MAX})}]?Set(COLLECTIONS_MSG_MAX=${COLLECTIONS_MSG_PLAYS_MAX}))',
        " same => n(play),Set(COLLECTIONS_MSG_PLAYS=$[${COLLECTIONS_MSG_PLAYS} + 1])",
        " same => n,Read(COLLECTIONS_MSG_KEY,${COLLECTIONS_MSG_SOUND}-message,1,,1,6)",
        ' same => n,GotoIf($["${COLLECTIONS_MSG_KEY}" = "1" & "${COLLECTIONS_MSG_TRANSFER}" = "1"]?transfer)',
        ' same => n,GotoIf($["${COLLECTIONS_MSG_KEY}" = "2"]?close)',
        " same => n,GotoIf($[${COLLECTIONS_MSG_PLAYS} < ${COLLECTIONS_MSG_MAX}]?play)",
        f" same => n,{_ev('result', ',Result: no_choice')}",
        " same => n,Hangup()",
        f" same => n(close),{_ev('key', ',Key: 2')}",
        ' same => n,GotoIf($["${COLLECTIONS_MSG_GOODBYE}" != "1"]?closed)',
        " same => n,Playback(${COLLECTIONS_MSG_SOUND}-goodbye)",
        f" same => n(closed),{_ev('result', ',Result: closed')}",
        " same => n,Hangup()",
        f" same => n(transfer),{_ev('key', ',Key: 1')}",
        f" same => n,Set(COLLECTIONS_MSG_UNTIL=$[${{EPOCH}} + {p['transfer_wait_seconds']}])",
        " same => n(pick),Set(COLLECTIONS_MSG_AGENT=)",
        f" same => n,AGI({agi}/collections-message-agent)",
        ' same => n,GotoIf($[${REGEX("^[0-9]{2,6}$" ${COLLECTIONS_MSG_AGENT})} != 1]?hold)',
        f" same => n,{_ev('member_ringing', ',Extension: ${COLLECTIONS_MSG_AGENT}')}",
        f" same => n,Dial(SIP/${{COLLECTIONS_MSG_AGENT}},{p['member_ring_seconds']},mU(collections-message-member-answered))",
        ' same => n,GotoIf($["${DIALSTATUS}" = "ANSWER"]?talked)',
        f" same => n,{_ev('member_missed', ',Extension: ${COLLECTIONS_MSG_AGENT},DialStatus: ${DIALSTATUS}')}",
        " same => n(hold),GotoIf($[${EPOCH} >= ${COLLECTIONS_MSG_UNTIL}]?noagent)",
        " same => n,MusicOnHold(default,5)",
        " same => n,Goto(pick)",
        " same => n(noagent),Playback(${COLLECTIONS_MSG_SOUND}-callback)",
        f" same => n,{_ev('result', ',Result: no_agent')}",
        " same => n,Hangup()",
        f" same => n(talked),{_ev('result', ',Result: transferred')}",
        " same => n,Hangup()",
        " same => n(bye),Hangup()",
        "exten => i,1,Hangup()",
        "exten => t,1,Hangup()",
        "exten => T,1,Hangup()",
        "",
        "; Runs on the MEMBER's channel once they answered (Dial U option).",
        "[collections-message-member-answered]",
        f"exten => s,1,{_ev('member_answered')}",
        " same => n,Return()",
        "",
        "; Hangup handler of Local;1: the call is over.",
        "[collections-message-ivr-end]",
        f"exten => s,1,{_ev('ended', ',Cause: ${HANGUPCAUSE}')}",
        " same => n,Return()",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    data = sys.stdin.read(65536 + 1)
    if len(data) > 65536:
        print("policy is larger than 64 KiB", file=sys.stderr)
        return 2
    try:
        sys.stdout.write(render(json.loads(data)))
    except (ValueError, MessageDialplanError) as e:
        print(f"invalid policy: {e}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
