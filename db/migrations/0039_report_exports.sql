-- 0039 report_exports (Phase 4, stream R0): private, asynchronous report exports.
--
-- One row per requested export (POST /v2/reports/<id>/exports). The worker claims it with
-- FOR UPDATE SKIP LOCKED, takes a fresh REPEATABLE READ snapshot, rechecks the requester's
-- permission at the start and again at publication, streams the rows in batches of 500 into
-- a private file (CSV, XLSX or the Arabic RTL XLSX) and records the metadata below.
--
--   status      queued -> running -> succeeded -> expired (artifact deleted by retention)
--               running -> retrying (lease expired / graceful stop) -> running ...
--               running | retrying -> failed (permission_denied, too_many_rows,
--               artifact_too_large, unknown_report, invalid_definition, internal_error,
--               max_attempts_exceeded)
--   definition  the normalized definition: {version, report, format, filters (normalized),
--               params (flat query form), sort, columns}. The export never re-reads the request.
--   cutoff_at   now() of the export snapshot: the data is exactly the database as of then.
--   totals      exact totals of the exported rows (money as decimal strings), same keys as the
--               preview's `totals`.
--   stored_path relative to BULK_STORAGE_DIR (reports/<yyyy>/<mm>/<id>-<attempt>.<ext>);
--               downloaded only through the API by the requester (creator-private).
--
-- No FK to users (legacy hard deletes). Locks: new table only. Instant.

CREATE TABLE IF NOT EXISTS report_exports (
    id               uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    report_id        text        NOT NULL CHECK (report_id ~ '^[A-Za-z0-9_-]{1,40}$'),
    format           text        NOT NULL CHECK (format IN ('csv', 'xlsx', 'xlsx_ar')),
    status           text        NOT NULL DEFAULT 'queued'
                     CHECK (status IN ('queued', 'running', 'retrying', 'succeeded', 'failed', 'expired')),
    definition       jsonb       NOT NULL CHECK (jsonb_typeof(definition) = 'object'),
    definition_sha256 text       NOT NULL CHECK (definition_sha256 ~ '^[0-9a-f]{64}$'),
    requested_by     uuid        NOT NULL,
    requested_at     timestamptz NOT NULL DEFAULT now(),
    started_at       timestamptz,
    cutoff_at        timestamptz,
    finished_at      timestamptz,
    rows_expected    bigint      CHECK (rows_expected >= 0),
    rows_written     bigint      NOT NULL DEFAULT 0 CHECK (rows_written >= 0),
    row_count        bigint      CHECK (row_count >= 0),
    totals           jsonb,
    file_name        text,
    stored_path      text,
    content_type     text,
    size_bytes       bigint      CHECK (size_bytes >= 0),
    sha256           text        CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    expires_at       timestamptz,
    purged_at        timestamptz,
    attempt          integer     NOT NULL DEFAULT 0 CHECK (attempt >= 0),
    max_attempts     integer     NOT NULL DEFAULT 3 CHECK (max_attempts >= 1),
    failed_attempts  integer     NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
    locked_by        text,
    lease_until      timestamptz,
    heartbeat_at     timestamptz,
    error_code       text,
    error_message    text,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    -- a running export always holds a lease; nothing else does
    CONSTRAINT report_exports_lease CHECK ((status = 'running') = (locked_by IS NOT NULL AND lease_until IS NOT NULL)),
    CONSTRAINT report_exports_finished CHECK ((status IN ('succeeded', 'failed', 'expired')) = (finished_at IS NOT NULL)),
    CONSTRAINT report_exports_published CHECK (
        status NOT IN ('succeeded', 'expired')
        OR (stored_path IS NOT NULL AND file_name IS NOT NULL AND size_bytes IS NOT NULL AND sha256 IS NOT NULL
            AND row_count IS NOT NULL AND totals IS NOT NULL AND cutoff_at IS NOT NULL AND expires_at IS NOT NULL)),
    CONSTRAINT report_exports_expired CHECK ((status = 'expired') = (purged_at IS NOT NULL)),
    CONSTRAINT report_exports_failed CHECK (status <> 'failed' OR error_code IS NOT NULL),
    CONSTRAINT report_exports_expiry CHECK (expires_at IS NULL OR expires_at > requested_at)
);

COMMENT ON TABLE report_exports IS
    'Private asynchronous report exports (Phase 4). Generated by the worker in a fresh REPEATABLE READ '
    'snapshot; the artifact is downloadable by the requester only and expires (retention purges the file).';
COMMENT ON COLUMN report_exports.definition IS
    'normalized definition {version, report, format, filters, params, sort, columns}; the worker builds its SQL from this';
COMMENT ON COLUMN report_exports.cutoff_at IS 'now() of the export snapshot (the data is as of this instant)';

CREATE INDEX IF NOT EXISTS ix_report_exports_claimable
    ON report_exports (requested_at, id) WHERE status IN ('queued', 'retrying');
CREATE INDEX IF NOT EXISTS ix_report_exports_leased
    ON report_exports (lease_until) WHERE status = 'running';
CREATE INDEX IF NOT EXISTS ix_report_exports_requester
    ON report_exports (requested_by, requested_at DESC);
CREATE INDEX IF NOT EXISTS ix_report_exports_expiry
    ON report_exports (expires_at) WHERE status = 'succeeded' AND purged_at IS NULL;
